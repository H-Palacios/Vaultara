class DocumentNames {
  const DocumentNames._();

  static const int maxLength = 30;

  /// [plain] is the localised word, such as "Passport". Returns [plain]
  /// unless the app is in English and the country is known.
  static String forCountry(
    String plain, {
    required String? mrzCountry,
    required String languageCode,
  }) {
    if (languageCode != 'en') return plain;
    final String? code = Countries.fromMrz(mrzCountry);
    final String? adjective = code == null ? null : adjectives[code];
    if (adjective == null) return plain;
    final String name = '$adjective $plain';
    return name.length > maxLength ? plain : name;
