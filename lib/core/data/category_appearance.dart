  /// The best icon for [name] from the word list, or null when none fits.
  static String? guessIcon(String name) {
    final text = ' ${TextSearch.fold(name)} ';
    String? best;
    var bestLength = 0;
    _words.forEach((icon, words) {
      for (final word in words) {
        // Match the start of a word, so "car" finds "car insurance" but not
        // "scarf", and keep the longest hit.
        if (text.contains(' $word') && word.length > bestLength) {
          best = icon;
          bestLength = word.length;
        }
      }
    });
    return best;
  }

  static List<String> searchIcons(String query, {int limit = 12}) {
    final text = TextSearch.fold(query).trim();
    if (text.length < 2) return const <String>[];
    final hits = <String>[];
    for (final key in icons.keys) {
      final words = <String>[
        ...key.split('_'),
        ...?_words[key],
        ...?_about[key]?.split(RegExp(r'[ ,]+')),
      ];
      final match = words.any(
        (word) =>
            word.startsWith(text) || (word.length > 2 && text.startsWith(word)),
      );
      if (match) {
        hits.add(key);
        if (hits.length == limit) break;
      }
    }
    return hits;
  }
